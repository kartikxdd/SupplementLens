    category: partial.category,
    subcategory: partial.subcategory || '',
    form: partial.form || 'powder', // powder | capsule | softgel | tablet | liquid
    typeLabel: partial.typeLabel,
    icon: partial.icon,
    summary: partial.summary || '',
    // serving / package
    servingSizeG: partial.servingSizeG,
    servingLabel: partial.servingLabel || `per ${partial.servingSizeG}g serving`,
    servingsPerContainer: partial.servingsPerContainer,
    packageSizeG: partial.packageSizeG || partial.defaultPackageG,
    defaultPackageG: partial.defaultPackageG || partial.packageSizeG,
    // macros (per serving)
    calories: partial.calories ?? 0,
    protein: partial.protein ?? 0,
    carbs: partial.carbs ?? 0,
    fat: partial.fat ?? 0,
    fiber: partial.fiber ?? 0,
    sugar: partial.sugar ?? 0,
    addedSugar: partial.addedSugar ?? 0,
    sodiumMg: partial.sodiumMg ?? 0,
    potassiumMg: partial.potassiumMg ?? 0,
    calciumMg: partial.calciumMg ?? 0,
    cholesterolMg: partial.cholesterolMg ?? 0,
    // actives
    activeDoseG: partial.activeDoseG ?? partial.protein ?? 0,
    activeName: partial.activeName || 'Active',
    actives: partial.actives || [], // [{ name, amount, unit }]
    aminoProfile: partial.aminoProfile || null, // { leucine, isoleucine, valine, ... }
    // quality
