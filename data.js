    sweeteners: partial.sweeteners || [],
    thickeners: partial.thickeners || [],
    colors: partial.colors || [],
    proprietaryBlend: partial.proprietaryBlend ?? false,
    allergens: partial.allergens || [],
    artificial: partial.artificial ?? false,
    // lab / trust
    thirdPartyTested: partial.thirdPartyTested ?? false,
    labName: partial.labName || null,
    labelAccuracyPct: partial.labelAccuracyPct ?? null, // claimed vs tested protein etc.
    heavyMetalsPass: partial.heavyMetalsPass ?? null,
